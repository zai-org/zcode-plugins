from __future__ import annotations

import os
import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path


SCRIPT = (
    Path(__file__).resolve().parents[1]
    / "skills"
    / "web-replicate"
    / "scripts"
    / "relink-node-modules.sh"
)
FAKE_DIGEST = "0123456789abcdef0123456789abcdef"


class NodeModulesCacheTest(unittest.TestCase):
    def setUp(self) -> None:
        self.tmp = tempfile.TemporaryDirectory(prefix="video2code cache test ")
        self.root = Path(self.tmp.name)
        self.cache = self.root / "cache with spaces"
        self.bin = self.root / "portable bin"
        self.cache.mkdir()
        self.bin.mkdir()
        self._install_required_commands()
        self._write_executable(
            "md5",
            "#!/bin/sh\n"
            "[ \"$#\" -eq 2 ] && [ \"$1\" = '-q' ] || exit 64\n"
            f"printf '%s\\n' '{FAKE_DIGEST}'\n",
        )
        real_mv = shutil.which("mv")
        assert real_mv is not None
        self._write_executable(
            "mv",
            "#!/bin/sh\n"
            "if [ \"${1:-}\" = '-T' ]; then\n"
            "  echo 'mv: illegal option -- T' >&2\n"
            "  exit 64\n"
            "fi\n"
            f"exec '{real_mv}' \"$@\"\n",
        )
        self.bash = shutil.which("bash")
        assert self.bash is not None

    def tearDown(self) -> None:
        self.tmp.cleanup()

    def _install_required_commands(self) -> None:
        # PATH is intentionally limited to this directory: md5sum must be
        # absent so the BSD `md5` fallback is exercised on Linux CI as well.
        for name in (
            "cp",
            "head",
            "ln",
            "ls",
            "mkdir",
            "mktemp",
            "nohup",
            "rm",
            "rmdir",
            "sleep",
            "tail",
        ):
            source = shutil.which(name)
            assert source is not None, name
            (self.bin / name).symlink_to(source)

    def _write_executable(self, name: str, content: str) -> None:
        path = self.bin / name
        path.write_text(content, encoding="utf-8")
        path.chmod(0o755)

    def _project(self, name: str) -> Path:
        project = self.root / name
        project.mkdir()
        (project / "package.json").write_text(
            '{"name":"portable-cache-test","private":true}\n',
            encoding="utf-8",
        )
        return project

    def _env(self, **extra: str) -> dict[str, str]:
        return {
            **os.environ,
            "PATH": str(self.bin),
            "NM_LOCAL_ROOT": str(self.cache),
            "TEMPLATE_NAME": "default",
            **extra,
        }

    def _run(
        self,
        project: Path,
        *args: str,
        env_extra: dict[str, str] | None = None,
    ) -> subprocess.CompletedProcess[str]:
        return subprocess.run(
            [self.bash, str(SCRIPT), str(project), *args],
            capture_output=True,
            text=True,
            env=self._env(**(env_extra or {})),
            timeout=10,
        )

    def test_bsd_tools_prepare_and_relink_paths_with_spaces(self) -> None:
        project = self._project("project with spaces")
        self._write_executable(
            "npm",
            "#!/bin/sh\n"
            "mkdir -p node_modules/.bin\n"
            ": > node_modules/.bin/vite\n",
        )

        prepared = self._run(project, "--prepare-only")
        self.assertEqual(prepared.returncode, 0, prepared.stderr or prepared.stdout)
        master = self.cache / f"master-default-{FAKE_DIGEST[:12]}"
        self.assertTrue((master / ".bin" / "vite").is_file())
        self.assertIn(f"✓ master ready: {master}", prepared.stdout)

        linked = self._run(project)
        self.assertEqual(linked.returncode, 0, linked.stderr or linked.stdout)
        self.assertTrue((project / "node_modules").is_symlink())
        self.assertTrue((project / "node_modules" / ".bin" / "vite").is_file())

    def test_concurrent_prepare_publishes_one_complete_master(self) -> None:
        project_one = self._project("project one")
        project_two = self._project("project two")
        barrier = self.root / "both builders reached npm"
        self._write_executable(
            "npm",
            "#!/bin/sh\n"
            ": > \"$TEST_BARRIER.$BUILDER_ID\"\n"
            "attempts=0\n"
            "while [ ! -e \"$TEST_BARRIER.one\" ] || [ ! -e \"$TEST_BARRIER.two\" ]; do\n"
            "  attempts=$((attempts + 1))\n"
            "  [ \"$attempts\" -lt 500 ] || exit 70\n"
            "  sleep 0.01\n"
            "done\n"
            "mkdir -p node_modules/.bin\n"
            "printf '%s\\n' \"$BUILDER_ID\" > node_modules/builder\n"
            ": > node_modules/.bin/vite\n",
        )

        common = {"TEST_BARRIER": str(barrier)}
        first = subprocess.Popen(
            [self.bash, str(SCRIPT), str(project_one), "--prepare-only"],
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
            env=self._env(**common, BUILDER_ID="one"),
        )
        second = subprocess.Popen(
            [self.bash, str(SCRIPT), str(project_two), "--prepare-only"],
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
            env=self._env(**common, BUILDER_ID="two"),
        )
        first_out, first_err = first.communicate(timeout=10)
        second_out, second_err = second.communicate(timeout=10)

        self.assertEqual(first.returncode, 0, first_err or first_out)
        self.assertEqual(second.returncode, 0, second_err or second_out)
        master = self.cache / f"master-default-{FAKE_DIGEST[:12]}"
        self.assertTrue((master / ".bin" / "vite").is_file())
        self.assertIn((master / "builder").read_text(encoding="utf-8").strip(), {"one", "two"})
        self.assertFalse((master / "node_modules").exists())
        self.assertEqual(list(self.cache.glob("*.publish-lock")), [])

    def test_failed_delta_install_does_not_publish_cloned_base(self) -> None:
        project = self._project("project with failed install")
        stale_base = self.cache / "master-default-previous"
        (stale_base / ".bin").mkdir(parents=True)
        (stale_base / ".bin" / "vite").write_text("old vite\n", encoding="utf-8")
        self._write_executable(
            "npm",
            "#!/bin/sh\n"
            "echo 'simulated npm failure' >&2\n"
            "exit 42\n",
        )

        prepared = self._run(project, "--prepare-only")

        self.assertNotEqual(prepared.returncode, 0)
        self.assertIn("npm install failed", prepared.stderr)
        master = self.cache / f"master-default-{FAKE_DIGEST[:12]}"
        self.assertFalse(master.exists())


if __name__ == "__main__":
    unittest.main()
