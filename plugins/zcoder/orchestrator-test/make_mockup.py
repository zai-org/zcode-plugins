import zlib, struct

W, H = 1200, 800
px = bytearray(W * H * 3)

def rect(x0, y0, x1, y1, color):
    r, g, b = color
    for y in range(max(0, y0), min(H, y1)):
        base = (y * W + max(0, x0)) * 3
        n = (min(W, x1) - max(0, x0)) * 3
        if n > 0:
            px[base:base + n] = bytes([r, g, b]) * (n // 3)

