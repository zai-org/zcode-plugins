def text(s, x, y, color, scale=2):
    r, g, b = color
    cx = x
    for ch in s.upper() if False else s:
        glyph = FONT.get(ch)
        if glyph is None:
            cx += 6 * scale; continue
        for ry, bits in enumerate(glyph):
            for rx in range(5):
                if bits & (0x10 >> rx):
                    rect(cx + rx*scale, y + ry*scale, cx + rx*scale + scale, y + ry*scale + scale, color)
        cx += 6 * scale

