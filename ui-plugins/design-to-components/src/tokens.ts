export interface TokenIssue { group: string; key: string; message: string }
const isColor = (v: string) => /^#([0-9a-f]{3}|[0-9a-f]{4}|[0-9a-f]{6}|[0-9a-f]{8})$/i.test(v) || /^(rgb|rgba|hsl|hsla|oklch|color-mix)\(/i.test(v) || v === "transparent";
const isLength = (v: string) => /^-?(\d+(\.\d+)?|\.\d+)(px|rem|em|%)?$/.test(v) || v === "0";

export function validateTokens(t: Tokens): TokenIssue[] {
  const out: TokenIssue[] = [];
  for (const g of GROUPS) for (const [k, v] of Object.entries(t[g] ?? {})) {
    if (!/^[a-z0-9][a-z0-9-]*$/.test(k)) out.push({ group: g, key: k, message: `Token name “${k}” must be lowercase letters, digits and dashes.` });
    if (typeof v !== "string" || !v.trim()) out.push({ group: g, key: k, message: "Empty value." });
    else if (g === "colors" && !isColor(v)) out.push({ group: g, key: k, message: `“${v}” is not a colour (#hex, rgb(), hsl(), oklch()).` });
    else if ((g === "fontSizes" || g === "radii" || g === "spacing") && !isLength(v)) out.push({ group: g, key: k, message: `“${v}” is not a length (px, rem, em, %).` });
    else if (/[;{}]/.test(v)) out.push({ group: g, key: k, message: "Value cannot contain ; { }." });
  }
  return out;
}

export const cssVar = (g: (typeof GROUPS)[number], k: string) => `--${PREFIX[g]}-${k}`;
export function tokensCss(t: Tokens): string {
  const lines = ["/* Generated by Design To Components from tokens.json — edit tokens.json, not this file. */", ":root {"];
  for (const g of GROUPS) for (const [k, v] of Object.entries(t[g] ?? {})) lines.push(`  ${cssVar(g, k)}: ${v};`);
  lines.push("}", "");
  return lines.join("\n");
}
export function tokensTs(t: Tokens): string {
  const body = GROUPS.map((g) => `  ${g}: {\n${Object.entries(t[g] ?? {}).map(([k, v]) => `    ${JSON.stringify(k)}: { value: ${JSON.stringify(v)}, css: "var(${cssVar(g, k)})" },`).join("\n")}\n  },`).join("\n");
  return `// Generated by Design To Components from tokens.json — edit tokens.json, not this file.\nexport const tokens = {\n${body}\n} as const;\nexport type Tokens = typeof tokens;\n`;
}
