// 设计变量：tokens.json → tokens.css（CSS 变量）+ tokens.ts（带类型的常量）。
export interface Tokens {
  colors: Record<string, string>;
  fonts: Record<string, string>;
  fontSizes: Record<string, string>;
  radii: Record<string, string>;
  spacing: Record<string, string>;
  shadows: Record<string, string>;
}
export const GROUPS = ["colors", "fonts", "fontSizes", "radii", "spacing", "shadows"] as const;
const PREFIX: Record<(typeof GROUPS)[number], string> = { colors: "color", fonts: "font", fontSizes: "font-size", radii: "radius", spacing: "space", shadows: "shadow" };

